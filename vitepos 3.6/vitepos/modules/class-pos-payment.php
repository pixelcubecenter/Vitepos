	/**
	 * The payment method name filter is generated by appsbd
	 *
	 * @param mixed $name It is name param.
	 * @param mixed $id It is id param.
	 *
	 * @return mixed|string
	 */
	public function payment_method_name_filter( $name, $id ) {
		$methods = self::get_payment_methods();
		foreach ( $methods as $method ) {
			if ( $method instanceof Payment_Method_Base ) {
				if ( $id == $method->id ) {
					$name = $method->title;
					break;
				}
			}
		}
		return $name;
	}
