	/**
	 * On every completed VitePOS order (online + offline) reconcile the credit
	 * ledger:
	 *  - create the debt row for the on-account ('N') portion;
	 *  - redeem store credit applied as the "From Account" discount (uid 'SC');
	 *  - add store credit purchased via the hidden Store Credit product.
	 * Each step is idempotent via its own order-meta guard.
	 *
	 * @param \WC_Order $order Its order param.
	 *
	 * @return void
	 */
	public function create_debt_on_complete( $order ) {
		if ( ! ( $order instanceof \WC_Order ) ) {
			return;
		}
		
		if ( ! \VitePos\Libs\VitePOS_Account_Service::is_feature_enabled() ) {
			return;
		}
		$customer_id = (int) $order->get_customer_id();
		if ( $customer_id <= 0 ) {
			return;
		}

		$order_id = $order->get_id();
		
		
		
		$outlet_id = (int) $order->get_meta( '_vt_outlet_id' );
		if ( $outlet_id <= 0 ) {
			$outlet_id = (int) $order->get_meta( '_vtp_outlet_id' );
		}
		$counter = (int) $order->get_meta( '_vt_counter_id' );
		if ( $counter <= 0 ) {
			$counter = (int) $order->get_meta( '_vtp_counter_id' );
		}
		$ctx_base  = array(
			'order_id'   => $order_id,
			'outlet_id'  => $outlet_id,
			'counter_id' => $counter,
		);

		
		if ( 'Y' === $order->get_meta( '_vt_credit_processed' ) ) {
			return;
		}

		
		
		
		
		$purpose = $order->get_meta( '_vt_collection_purpose' );
		if ( 'C' === $purpose || 'D' === $purpose ) {
			
			
			
			
			
			if ( 'Y' !== vitepos_wc_get_meta( $order->get_id(), '_vt_is_paid' ) ) {
				return;
			}
			$amount = round( (float) $order->get_total(), 4 );
			
			
			
			$target_debt_id = (int) $order->get_meta( '_vt_target_debt_id' );
			if ( $target_debt_id > 0 ) {
				\VitePos\Libs\VitePOS_Account_Service::add_targeted_credit( $customer_id, $amount, $target_debt_id, $ctx_base );
			} else {
				\VitePos\Libs\VitePOS_Account_Service::add_credit( $customer_id, $amount, $ctx_base, 'debt_repay' );
			}
			$order->update_meta_data( '_vt_credit_processed', 'Y' );
			$order->save();
			return;
		}

		
		$payment_list = $order->get_meta( '_vtp_payment_list' );
		if ( is_string( $payment_list ) ) {
			$payment_list = json_decode( $payment_list, true );
		}
		if ( ! is_array( $payment_list ) ) {
			return;
		}

		foreach ( $payment_list as $line ) {
			$type   = isset( $line['type'] ) ? $line['type'] : '';
			$amount = isset( $line['amount'] ) ? round( (float) $line['amount'], 4 ) : 0.0;
			if ( $amount <= 0 ) {
				continue;
			}
			if ( 'N' === $type ) {
				\VitePos\Libs\VitePOS_Account_Service::add_debit( $customer_id, $amount, $ctx_base );
			} elseif ( 'X' === $type ) {
				\VitePos\Libs\VitePOS_Account_Service::redeem_credit( $customer_id, $amount, $ctx_base );
			}
		}

		$order->update_meta_data( '_vt_credit_processed', 'Y' );
		$order->save();
	}

	/**
	 * Reverse the credit/debit effect of a cancelled or refunded order using
	 * add-only compensating entries (no subtraction, no row mutation). Each
	 * original ledger row of the order gets an opposite entry so that net
	 * returns to its pre-order value.
	 *
	 * @param int $order_id The order id.
	 *
	 * @return void
	 */
	public function reverse_credit_on_void( $order_id ) {
		$order = wc_get_order( $order_id );
		if ( ! $order ) {
			return;
		}
		if ( 'Y' !== $order->get_meta( '_vt_credit_processed' ) ) {
			return; 
		}
		if ( 'Y' === $order->get_meta( '_vt_credit_reversed' ) ) {
			return; 
		}
		if ( 'Y' === $order->get_meta( '_vt_refund_ledger_handled' ) ) {
			return; 
		}
		$customer_id = (int) $order->get_customer_id();
		if ( $customer_id <= 0 ) {
			return;
		}

		global $wpdb;
		$ledger = $wpdb->prefix . 'apbd_pos_credit_ledger';
		$ctx    = array(
			'order_id' => $order->get_id(),
			'note'     => 'Reversal: order voided',
		);

		// phpcs:ignore WordPress.DB.PreparedSQL.InterpolatedNotPrepared
		$rows = $wpdb->get_results(
			$wpdb->prepare( "SELECT entry_type, amount FROM {$ledger} WHERE order_id = %d", $order->get_id() )
		);

		foreach ( (array) $rows as $r ) {
			$amount = round( (float) $r->amount, 4 );
			if ( $amount <= 0 ) {
				continue;
			}
			if ( 'credit_topup' === $r->entry_type || 'debt_repay' === $r->entry_type ) {
				
				\VitePos\Libs\VitePOS_Account_Service::add_debit( $customer_id, $amount, $ctx, 'credit_redeem' );
			} elseif ( 'debt_incur' === $r->entry_type || 'credit_redeem' === $r->entry_type ) {
				
				\VitePos\Libs\VitePOS_Account_Service::add_credit( $customer_id, $amount, $ctx, 'debt_repay' );
			}
		}

		$order->update_meta_data( '_vt_credit_reversed', 'Y' );
		$order->save();
	}

	/**
	 * Break an order's payment list into the three refund buckets. Reads
	 * `_vtp_payment_list` (JSON): type 'N' = on-account debt, type 'X' = redeemed
	 * store credit, everything else (cash/card/terminal) = real money.
	 *
	 * @param \WC_Order $order The order.
	 *
	 * @return array{ debt: float, credit: float, cash: float }
	 */
	public static function refund_payment_composition( $order ) {
		$debt   = 0.0;
		$credit = 0.0;
		$cash   = 0.0;
		$list   = $order->get_meta( '_vtp_payment_list' );
		if ( is_string( $list ) ) {
			$list = json_decode( $list, true );
		}
		if ( is_array( $list ) ) {
			foreach ( $list as $line ) {
				$type   = isset( $line['type'] ) ? $line['type'] : '';
				$amount = isset( $line['amount'] ) ? round( (float) $line['amount'], 4 ) : 0.0;
				if ( $amount <= 0 ) {
					continue;
				}
				if ( 'N' === $type ) {
					$debt = round( $debt + $amount, 4 );
				} elseif ( 'X' === $type ) {
					$credit = round( $credit + $amount, 4 );
				} else {
					$cash = round( $cash + $amount, 4 );
				}
			}
		}
		return array(
			'debt'   => $debt,
			'credit' => $credit,
			'cash'   => $cash,
		);
	}

	/**
	 * Decide whether the debt/credit ledger should handle this refund and, if so,
	 * mark the order BEFORE wc_create_refund() runs so the full-refund status flip's
	 * reverse_credit_on_void() early-returns instead of double-reversing.
	 *
	 * @param \WC_Order $order   The order being refunded.
	 * @param bool      $is_full Whether this is a full refund (kept for symmetry/future use).
	 *
	 * @return bool True when claimed.
	 */
	public static function claim_refund_if_applicable( $order, $is_full ) {
		if ( ! ( $order instanceof \WC_Order ) ) {
			return false;
		}
		if ( ! \VitePos\Libs\VitePOS_Account_Service::is_feature_enabled() ) {
			return false;
		}
		if ( (int) $order->get_customer_id() <= 0 ) {
			return false;
		}
		$comp = self::refund_payment_composition( $order );
		if ( $comp['debt'] <= 0 && $comp['credit'] <= 0 ) {
			return false; 
		}
		$order->update_meta_data( '_vt_refund_ledger_handled', 'Y' );
		$order->save();
		return true;
	}

	/**
	 * Clear the claim guard (used when wc_create_refund() fails so no stale state remains).
	 *
	 * @param \WC_Order $order The order.
	 *
	 * @return void
	 */
	public static function unclaim_refund( $order ) {
		if ( ! ( $order instanceof \WC_Order ) ) {
			return;
		}
		if ( $order->meta_exists( '_vt_refund_ledger_handled' ) ) {
			$order->delete_meta_data( '_vt_refund_ledger_handled' );
			$order->save();
		}
	}

	/**
	 * Post the credit/debt side of a refund and return the cash/debt/credit split.
	 * Only acts on orders claimed by claim_refund_if_applicable(). Add-only: debt is
	 * reduced with a compensating credit (tagged to the order's own invoice, FIFO-
	 * clamped; any excess untagged → store credit). Redeemed store credit is returned
	 * with an untagged credit. The cash portion is handled by the caller (drawer).
	 *
	 * @param \WC_Order        $order         The order.
	 * @param \WC_Order_Refund $refund        The refund just created.
	 * @param bool             $is_full       Whether this was a full refund.
	 * @param float            $refund_amount The refunded amount.
	 *
	 * @return array{ to_debt: float, to_credit: float, to_cash: float }|null Null when not claimed.
	 */
	public static function apply_refund_ledger( $order, $refund, $is_full, $refund_amount ) {
		if ( ! ( $order instanceof \WC_Order ) ) {
			return null;
		}
		
		
		
		$order = wc_get_order( $order->get_id() );
		if ( ! $order ) {
			return null;
		}
		if ( 'Y' !== $order->get_meta( '_vt_refund_ledger_handled' ) ) {
			return null; 
		}
		$customer_id = (int) $order->get_customer_id();
		if ( $customer_id <= 0 ) {
			return null;
		}

		$comp         = self::refund_payment_composition( $order );
		$prior_debt   = (float) $order->get_meta( '_vt_re_to_debt' );
		$prior_credit = (float) $order->get_meta( '_vt_re_to_credit' );
		$prior_cash   = (float) $order->get_meta( '_vt_re_to_cash' );

		$split = \VitePos\Libs\VitePOS_Debt_FIFO_Core::allocate_refund(
			$comp['debt'],
			$comp['credit'],
			$comp['cash'],
			$prior_debt,
			$prior_credit,
			$prior_cash,
			(float) $refund_amount
		);

		$outlet_id = (int) $order->get_meta( '_vt_outlet_id' );
		if ( $outlet_id <= 0 ) {
			$outlet_id = (int) $order->get_meta( '_vtp_outlet_id' );
		}
		$counter = (int) $order->get_meta( '_vt_counter_id' );
		if ( $counter <= 0 ) {
			$counter = (int) $order->get_meta( '_vtp_counter_id' );
		}
		$ctx = array(
			'order_id'   => $order->get_id(),
			'outlet_id'  => $outlet_id,
			'counter_id' => $counter,
			'note'       => 'Refund #' . $refund->get_id(),
		);

		
		if ( $split['to_debt'] > 0 ) {
			global $wpdb;
			$ledger    = $wpdb->prefix . 'apbd_pos_credit_ledger';
			// phpcs:ignore WordPress.DB.PreparedSQL.InterpolatedNotPrepared
			$debit_row = $wpdb->get_row(
				$wpdb->prepare(
					"SELECT id, amount FROM {$ledger} WHERE order_id = %d AND entry_type = 'debt_incur' ORDER BY id ASC LIMIT 1",
					$order->get_id()
				)
			);
			$tagged   = 0.0;
			$debit_id = $debit_row ? (int) $debit_row->id : 0;
			if ( $debit_id > 0 ) {
				$open_remaining = 0.0;
				$snapshot       = \VitePos\Libs\VitePOS_Account_Service::fifo_snapshot( $customer_id );
				if ( ! empty( $snapshot['open_debts'] ) ) {
					foreach ( $snapshot['open_debts'] as $od ) {
						if ( (int) $od['id'] === $debit_id ) {
							$open_remaining = round( (float) $od['remaining'], 4 );
							break;
						}
					}
				}
				$tagged = min( $split['to_debt'], $open_remaining );
				if ( $tagged > 0 ) {
					\VitePos\Libs\VitePOS_Account_Service::add_targeted_credit( $customer_id, $tagged, $debit_id, $ctx );
				}
			}
			$untagged = round( $split['to_debt'] - $tagged, 4 );
			if ( $untagged > 0 ) {
				\VitePos\Libs\VitePOS_Account_Service::add_credit( $customer_id, $untagged, $ctx, 'debt_repay' );
			}
		}

		
		if ( $split['to_credit'] > 0 ) {
			\VitePos\Libs\VitePOS_Account_Service::add_credit( $customer_id, $split['to_credit'], $ctx, 'debt_repay' );
		}

		
		$order->update_meta_data( '_vt_re_to_debt', round( $prior_debt + $split['to_debt'], 4 ) );
		$order->update_meta_data( '_vt_re_to_credit', round( $prior_credit + $split['to_credit'], 4 ) );
		$order->update_meta_data( '_vt_re_to_cash', round( $prior_cash + $split['to_cash'], 4 ) );
		$order->update_meta_data( '_vt_credit_reversed', 'Y' ); 
		$order->save();

		return $split;
