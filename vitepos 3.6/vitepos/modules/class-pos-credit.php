	/**
	 * Build the unified debit/credit ledger rows for a customer (frontend shape).
	 *
	 * Maps each account-statement entry onto the field names the admin ledger modal
	 * binds to, deriving a human "Description" label from the entry_type.
	 *
	 * @param int $customer_id Customer id.
	 * @param int $limit Page size.
	 * @param int $page Page (1-based).
	 *
	 * @return array Array of row objects.
	 */
	private function build_ledger_rows( $customer_id, $limit = 50, $page = 1 ) {
		$rows   = VitePOS_Account_Service::get_statement( $customer_id, $limit, $page );
		$ledger = array();
		$index  = ( max( 1, $page ) - 1 ) * max( 1, $limit );
		
		$labels = array(
			'credit_topup'  => 'Store credit added',
			'debt_repay'    => 'Repayment',
			'debt_incur'    => 'On-account purchase',
			'credit_redeem' => 'Store credit used',
		);
		foreach ( $rows as $row ) {
			$entry_type = isset( $row['entry_type'] ) ? $row['entry_type'] : '';
			$title      = isset( $labels[ $entry_type ] )
				? $labels[ $entry_type ]
				: ( 'C' === $row['type'] ? 'Store credit added' : 'Store credit used' );
			$ledger[] = (object) array(
				'id'              => ++$index,
				'type'            => $row['type'],
				'entry_type'      => $entry_type,
				'amount'          => (float) $row['amount'],
				'pre_balance'     => isset( $row['prev_balance'] ) ? (float) $row['prev_balance'] : 0.0,
				'balance'         => (float) $row['balance'],
				'reference_type'  => '',
				'reference_label' => '',
				'reference_id'    => '',
				'order_id'        => isset( $row['order_id'] ) ? (int) $row['order_id'] : 0,
				'title'           => $title,
				'note'            => $row['note'],
				'created_at'      => appsbd_get_wp_datetime_with_format($row['created_at']),
			);
		}
		return $ledger;
	}

	/**
	 * Record an admin-side repayment (specific invoice or bulk FIFO).
	 */
	public function payment() {
		$main_response = new Ajax_Confirm_Response();
		if ( $this->debt_disabled() ) {
			$this->add_error( __( 'The Debt / On Account feature is disabled.', 'vitepos' ) );
			$main_response->display_with_response( false );
			return;
		}
		$customer_id   = (int) AppInput::post_value( 'customer_id' );
		$amount        = (float) AppInput::post_value( 'amount', 0 );
		$method        = AppInput::post_value( 'method', '' );
		$note          = AppInput::post_value( 'note', '' );
		$settle        = AppInput::post_value( 'settle_remaining_as_credit', 'N' );
		$outlet_id     = (int) AppInput::post_value( 'outlet_id', 0 );
		$counter_id    = (int) AppInput::post_value( 'counter_id', 0 );

		
		$result = VitePOS_Collection_Order::create(
			array(
				'customer_id'                => $customer_id,
				'purpose'                    => 'D',
				'amount'                     => $amount,
				'method'                     => $method,
				'note'                       => $note,
				'settle_remaining_as_credit' => ( 'Y' === $settle ),
				'outlet_id'                  => $outlet_id,
				'counter_id'                 => $counter_id,
			)
		);
		if ( ! $result->is_ok ) {
			$this->add_error( $result->message );
			$main_response->display_with_response( false );
			return;
		}
		$this->add_info( 'Repayment recorded successfully' );
		$main_response->display_with_response(
			true,
			(object) array(
				'order_id' => $result->order_id,
				'summary'  => VitePOS_Account_Service::get_summary( $customer_id ),
			)
		);
	}

