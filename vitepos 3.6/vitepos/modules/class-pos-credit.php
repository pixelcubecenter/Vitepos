	/**
	 * Pull a search string out of the grid's src_by structure.
	 *
	 * @param array $src_by Its src_by param.
	 *
	 * @return string
	 */
	private function extract_search( $src_by ) {
		if ( ! is_array( $src_by ) ) {
			return '';
		}
		foreach ( $src_by as $item ) {
			if ( is_array( $item ) && ! empty( $item['val'] ) ) {
				return is_string( $item['val'] ) ? $item['val'] : '';
			}
			if ( is_object( $item ) && ! empty( $item->val ) ) {
				return is_string( $item->val ) ? $item->val : '';
			}
		}
		return '';
	}

	/**
	 * Build a short "items purchased" string from a WC order.
	 *
	 * @param int $order_id Its order_id param.
	 *
	 * @return string
	 */
	private function get_order_items_text( $order_id ) {
		if ( empty( $order_id ) ) {
			return '';
		}
		$order = wc_get_order( $order_id );
		if ( ! $order ) {
			return '';
		}
		$parts = array();
		foreach ( $order->get_items() as $item ) {
			$parts[] = $item->get_quantity() . '× ' . $item->get_name();
		}
		return implode( ', ', $parts );
	}
}
