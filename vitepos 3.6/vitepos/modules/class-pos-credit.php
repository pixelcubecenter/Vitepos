	/**
	 * Map outlet-ledger rows onto the frontend field names the log grid binds to.
	 *
	 * Derives a human "Description" from the entry_type and resolves the customer
	 * display name for each row.
	 *
	 * @param array $rows Statement-style rows from the account service.
	 *
	 * @return array Array of row objects.
	 */
	private function decorate_ledger_rows( $rows ) {
		
		$labels = array(
			'credit_topup'  => 'Store credit added',
			'debt_repay'    => 'Repayment',
			'debt_incur'    => 'On-account purchase',
			'credit_redeem' => 'Store credit used',
		);
		$index  = 0;
		$ledger = array();
		foreach ( $rows as $row ) {
			$entry_type = isset( $row['entry_type'] ) ? $row['entry_type'] : '';
			$title      = isset( $labels[ $entry_type ] )
				? $labels[ $entry_type ]
				: ( 'C' === $row['type'] ? 'Store credit added' : 'Store credit used' );
			$user       = get_userdata( (int) $row['customer_id'] );
			$ledger[]   = (object) array(
				'id'            => ++$index,
				'type'          => $row['type'],
				'entry_type'    => $entry_type,
				'customer_id'   => (int) $row['customer_id'],
				'customer_name' => $user->first_name ?  ($user->first_name . ' ' . $user->last_name) : $user->display_name,
				'amount'        => (float) $row['amount'],
				'pre_balance'   => isset( $row['prev_balance'] ) ? (float) $row['prev_balance'] : 0.0,
				'balance'       => (float) $row['balance'],
				'order_id'      => isset( $row['order_id'] ) ? (int) $row['order_id'] : 0,
				'title'         => $title,
				'note'          => $row['note'],
				'created_at'    => $row['created_at'],
			);
		}
		return $ledger;
	}

