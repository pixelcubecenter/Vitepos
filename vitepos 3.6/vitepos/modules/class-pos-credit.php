	/**
	 * Credit Customers grid (manager screen).
	 */
	public function data() {
		$main_response = new Ajax_Data_Response();
		$page          = AppInput::get_value( 'page', 1 );
		$limit         = AppInput::get_value( 'limit', 100 );
		if ( $this->debt_disabled() ) {
			$main_response->display_grid_response();
			return;
		}

		$main_response->set_download_filename( 'credit-customers' );

		$target_roles = array( 'customer', 'subscriber' );

		$args = array(
			'count_total' => true,
			'number'      => $limit,
			'paged'      =>$page,
		);

		POS_Customer::set_search_param( AppInput::post_value('src_by', array()), $args );
		POS_Customer::set_sort_param( AppInput::post_value( 'sort_by', array() ), $args );

		$args = wp_parse_args( $args );
		$user_search = new \WP_User_Query( $args );
		$records     = (int) $user_search->get_total();

		$main_response->set_grid_records( $records );

		$rows = array();

		foreach ( $user_search->get_results() as $user ) {

				$credit = VitePOS_Credit_Settings::get_credit_info( $user->ID );
				$name   = trim( $user->first_name . ' ' . $user->last_name );

				$rows[] = (object) array(
					'id'             => $user->ID,
					'name'           => '' !== $name ? $name : $user->user_nicename,
					'email'          => $user->user_email,
					'contact_no'     => $user->billing_phone,
					'credit_enabled' => $credit->credit_enabled,
					'credit_limit'   => $credit->credit_limit,
					'current_debt'   => $credit->current_debt,
					'store_credit'   => $credit->store_credit,
				);
		}

		$main_response->set_grid_data( $rows );
		$main_response->display_grid_response();
	}

	/**
	 * Global debt ledger grid (all customers).
	 */
	public function debt_list() {
		$main_response = new Ajax_Data_Response();
		if ( $this->debt_disabled() ) {
			$main_response->display_grid_response();
			return;
		}
		$main_response->set_download_filename( 'debt-ledger' );

		
		$mainobj = new Mapbd_Pos_Credit_Ledger();
		$mainobj->set_search_by_param( $main_response->src_by, 'customer_id,order_id,status,outlet_id' );
		$mainobj->set_sort_by_param( $main_response->sort_by );

		
		$multiparam               = is_array( $main_response->multiparam ) ? $main_response->multiparam : array();
		$multiparam['entry_type'] = 'debt_incur';

		$records = $mainobj->count_aLL( $main_response->src_item, $main_response->src_text, $multiparam, 'after' );
		if ( $records > 0 ) {
			$main_response->set_grid_records( $records );
			$result = $mainobj->select_all_grid_data(
				'',
				'created_at',
				'desc',
				$main_response->limit,
				$main_response->limit_start(),
				$main_response->src_item,
				$main_response->src_text,
				$multiparam,
				'after'
			);
			$labels = $mainobj->get_property_raw_options( 'status' );
			if ( $result ) {
				foreach ( $result as &$row ) {
					$user               = get_userdata( (int) $row->customer_id );
					$row->customer_name = $user ? $user->display_name : '';
					
					
					
					$row->total_amount = round( (float) $row->amount, 4 );
					$row->prev_balance = round( (float) $row->prev_balance, 4 );
					$row->status_label = isset( $labels[ $row->status ] ) ? $labels[ $row->status ] : $row->status;
				}
			}
			$main_response->set_grid_data( $result );
		}
		$main_response->display_grid_response();
	}

	/**
	 * Enable credit and set a per-customer limit.
	 */
	public function set_limit() {
		$main_response = new Ajax_Confirm_Response();
		if ( $this->debt_disabled() ) {
			$this->add_error( __( 'The Debt / On Account feature is disabled.', 'vitepos' ) );
			$main_response->display_with_response( false );
			return;
		}
		$customer_id   = (int) AppInput::post_value( 'customer_id' );
		$enabled       = AppInput::post_value( 'enabled', 'N' );
		$limit         = AppInput::post_value( 'limit', null );
		if ( empty( $customer_id ) ) {
			$this->add_error( 'Customer is required' );
			$main_response->display_with_response( false );
			return;
		}
		if ( VitePOS_Credit_Settings::set_customer_credit( $customer_id, $enabled, $limit ) ) {
			$this->add_info( 'Credit settings updated' );
			$main_response->display_with_response( true, VitePOS_Credit_Settings::get_credit_info( $customer_id ) );
		} else {
			$this->add_error( 'Failed to update credit settings' );
			$main_response->display_with_response( false );
		}
	}

	/**
	 * Summary totals + credit info for a customer.
	 */
	public function debt_summary() {
		$main_response = new Ajax_Confirm_Response();
		if ( $this->debt_disabled() ) {
			$main_response->display_with_response( true, array() );
			return;
		}
		$customer_id   = (int) AppInput::post_value( 'customer_id' );
		if ( empty( $customer_id ) ) {
			$this->add_error( 'Customer is required' );
			$main_response->display_with_response( false );
			return;
		}
		$limit                     = (int) AppInput::post_value( 'limit', 200 );
		$page                      = (int) AppInput::post_value( 'page', 1 );
		$summary                   = VitePOS_Account_Service::get_summary( $customer_id );
		$credit                    = VitePOS_Account_Service::get_credit_info( $customer_id );
		$summary->credit_enabled   = $credit->credit_enabled;
		$summary->credit_limit     = $credit->credit_limit;
		$summary->available_credit = $credit->available_credit;
		$summary->store_credit     = $credit->store_credit;
		
		
		$summary->store_credit_total = $credit->store_credit;
		
		$summary->ledger = $this->build_ledger_rows( $customer_id, $limit, $page );
		$main_response->display_with_response( true, $summary );
	}

	/**
	 * Per-customer unified ledger as an elite-grid response.
	 *
	 * Returns server-paged ledger rows (newest first) in the grid envelope the
	 * admin elite-grid consumes, and piggybacks the header `summary` so the
	 * Account Ledger modal loads both in a single request.
	 */
	public function customer_ledger() {
		$main_response = new Ajax_Data_Response();
		if ( $this->debt_disabled() ) {
			$main_response->display_grid_response();
			return;
		}
		$main_response->set_download_filename( 'customer-ledger' );
		$customer_id = (int) AppInput::post_value( 'customer_id' );
		if ( empty( $customer_id ) ) {
			$main_response->display_grid_response();
			return;
		}
		$total = VitePOS_Account_Service::count_statement( $customer_id );
		if ( $total > 0 ) {
			$main_response->set_grid_records( $total );
			$limit = empty( $main_response->limit ) ? $total : (int) $main_response->limit;
			$main_response->set_grid_data( $this->build_ledger_rows( $customer_id, $limit, $main_response->page ) );
		}
		
		
		$main_response->add_additional_property( 'summary', VitePOS_Account_Service::get_summary( $customer_id ) );
		$main_response->display_grid_response();
	}

