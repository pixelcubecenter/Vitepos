	/**
	 * The set route permission is generated by appsbd
	 *
	 * @param \VitePos\Libs\any $route Its string.
	 *
	 * @return bool|void
	 */
	public function set_route_permission( $route ) {
		
		switch ( $route ) {
			case 'dashboard-report':
				return current_user_can( 'report-menu' );
			case 'order-report':
				return current_user_can( 'report-order' );
			case 'product-report':
			case 'product-report-download':
			case 'product-info':
			case 'product-details-report':
				return current_user_can( 'report-product' );
			case 'purchase-report':
				return current_user_can( 'report-purchase' );
			case 'customer-report':
				return current_user_can( 'report-customer' );
			case 'staff-report':
				return current_user_can( 'report-staff' );
			default:
				return current_user_can( 'report-menu' );
		}
	}

	/**
	 * The order report is generated by appsbd
	 *
	 * @return \Appsbd\V1\libs\API_Response
	 */
	public function order_report() {
		$response_data = new API_Data_Response();
		$args          = array(
			'status'        => array( POS_Settings::def_oder_status(), 'completed' ),
			'limit'         => $this->get_payload( 'limit', 20 ),
			'page'          => $this->get_payload( 'page', 1 ),
			'orderby'       => 'date',
			'order'         => $this->get_payload( 'order', 'DESC'),
			'paginate'      => true,
			'vt_meta_query' => array(
				array(
					'key'     => '_is_vitepos',
					'value'   => 'Y',
					'compare' => '=',
				),
			),
		);
		if ( ! POS_Settings::is_admin_user() && ! current_user_can( 'can-refund-any-order' ) ) {
			$outlets = get_user_meta( $this->get_current_user_id(), 'outlet_id', true );
			if ( is_array( $outlets ) ) {
				$args['vt_meta_query'][] = array(
					'key'     => '_vtp_outlet_id',
					'value'   => $outlets,
					'compare' => 'IN',
				);
			} else {
				$this->add_error( "You don't have permission to view details of this outlet" );
				$response_data->set_total_records( 0 );
				$this->response->set_response( false, '', $response_data );

				return $this->response->get_response();
			}
		}
		$src_props     = $this->get_payload( 'src_by', array() );
		$sort_by_props = $this->get_payload( 'sort_by', array() );
		POS_Order::order_search_props( $args, $src_props );
		POS_Order::order_sort_param( $sort_by_props, $args );

		$orders = wc_get_orders( $args );

		$orderlist = array();
		if ( ! empty( $orders->orders ) && is_array( $orders->orders ) ) {
			foreach ( $orders->orders as $order ) {
				$v_order = new \stdClass();
				if ($order instanceof \WC_Order) {
					$v_order->order_id = $order->get_id();
					$create_date = $order->get_date_created();
					$v_order->order_c_date = appsbd_get_wp_datetime_with_format($create_date);
					$v_order->payment_list = $order->get_meta('_vtp_payment_list');
					$v_order->tax_total = (float) $order->get_total_tax('view');
					$counter_id = $order->get_meta('_vtp_counter_id');
					$v_order->grand_total = floatval($order->get_total(''));
					$v_order->is_tax_in = $order->get_prices_include_tax();
					$counter_obj = null;

					$include_tax = $order->get_prices_include_tax();
					if ($include_tax) {
						if ('A' == $v_order->tax_method) {
							if ($order->meta_exists('_vt_sub_total')) {
								$v_order->sub_total = vitepos_wc_amount($order->get_meta('_vt_sub_total'));
							} else {
								$v_order->sub_total = vitepos_wc_amount($order->get_subtotal()) + vitepos_wc_amount($order->get_total_tax('view')) + vitepos_wc_amount($order->get_discount_tax('view'));
							}
						} else {
							if ($order->meta_exists('_vt_sub_total')) {
								$v_order->sub_total = vitepos_wc_amount($order->get_meta('_vt_sub_total'));
							} else {
								$v_order->sub_total = $order->get_subtotal() + $order->get_total_tax();
							}
						}
					} else {
						$v_order->sub_total = $order->get_subtotal();
					}

					$v_order->c_fees = [];
					$v_order->c_discounts = [];
					$v_order->fees = [];
					$v_order->discounts = [];
					foreach ($order->get_items('fee') as $item) {	
						if ($item instanceof \WC_Order_Item_Fee) {
							$dis_fee_obj = new \stdClass();
							$dis_fee_obj->type = $item->get_meta('_vtp_cal_type');
							$dis_fee_obj->val = floatval($item->get_meta('_vtp_cal_val'));
							if ( "P" == $dis_fee_obj->type ) {
								$dis_fee_obj->amount = round(floatval(($v_order->sub_total * $dis_fee_obj->val) / 100),2);
							} else {
								$dis_fee_obj->amount = round(floatval($dis_fee_obj->val),2);
							}
							
							if ($item->meta_exists('_vtp_custom_type')) {
								$dis_fee_obj->title = $item->get_meta('_vtp_title');
								$dis_fee_obj->rule_type = $item->get_meta('_vtp_custom_type');
								$dis_fee_obj->is_taxable = 'N';
								if ($item->meta_exists('_vtp_is_taxable')) {	
									$dis_fee_obj->is_taxable = $item->get_meta('_vtp_is_taxable');
								}
								if ($item->meta_exists('_vtp_fee_uid')) {
									$dis_fee_obj->uid = $item->get_meta('_vtp_fee_uid');
								}
								if ($item->meta_exists('_vtp_dis_uid')) {
									$dis_fee_obj->uid = $item->get_meta('_vtp_dis_uid');
								}
								if ($item->get_total() > 0) {
									
									$v_order->c_fees[] = $dis_fee_obj;
								} else {
									
									$v_order->c_discounts[] = $dis_fee_obj;
								}
							} elseif ($item->get_total() > 0) {
								
								if (empty($dis_fee_obj->amount)) {
									$dis_fee_obj->amount = appsbd_wc_amount($item->get_total());
								}
								$v_order->fees[] = $dis_fee_obj;
							} else {
								
								if (empty($dis_fee_obj->amount)) {
									$dis_fee_obj->amount = appsbd_wc_amount(abs($item->get_total()));
								}
								$v_order->discounts[] = $dis_fee_obj;
							}
						}
					}

					$v_order->coupon_discount = $order->get_total_discount(!$v_order->is_tax_in);

					
					if ($v_order->is_tax_in) { 
						$vt_coupons = $order->get_meta('_vt_coupons');
						if (!empty($vt_coupons) && is_array($vt_coupons)) {
							$coupon_discount = 0.0;
							foreach ($vt_coupons as $vt_coupon) {
								if (!empty($vt_coupon['amount'])) {
									$coupon_discount += $vt_coupon['amount'];
								}
							}
							if (!empty($coupon_discount) && ($coupon_discount > 0)) {
								$v_order->coupon_discount = $coupon_discount;
							}
						}
					}
					if (!empty($counter_id)) {
						$counter_obj = Mapbd_Pos_Counter::find_by('id', $counter_id);
					}
					$v_order->counter = $counter_obj;

					$processed_by = $order->get_meta('_vtp_processed_by');
					if (!empty($processed_by)) {
						$user = get_user_by('id', $processed_by);
						$v_order->processed_by = new \stdClass();
						$v_order->processed_by->id = $processed_by;
						$v_order->processed_by->name = !empty($user) ? appsbd_get_user_title_by_user($user) : 'Unknown';
					} elseif (!metadata_exists('post', $v_order->order_id, '_vtp_processed_by')) {
						$v_order->processed_by = new \stdClass();
						$v_order->processed_by->id = null;
						$v_order->processed_by->name = 'Online';
					} else {
						$v_order->processed_by = new \stdClass();
						$v_order->processed_by->id = null;
						$v_order->processed_by->name = 'Unknown';
					}
				}
				$orderlist[] = $v_order;
			}
		}

		$page                 = $this->get_payload( 'page', 1 );
		$limit                = $this->get_payload( 'limit', 20 );
		$response_data->page  = $page;
		$response_data->limit = $limit;
		$type                 = $this->get_payload( 'request_type', '' );
		if ( ! empty( $type ) && 'pdf' == $type ) {
			if ( ! empty( $orders->total ) ) {
				$limit                = $this->set_limit( $orders->total );
				$response_data->limit = $limit;
			}
		}

		if ( $response_data->set_total_records( $orders->total ) ) {
			$response_data->rowdata = $orderlist;
		}

		$this->response->set_response( true, 'Order found', $response_data );

		return $this->response;
	}

	/**
	 * The purchase report is generated by appsbd
	 *
	 * @return \Appsbd\V1\libs\API_Response
	 */
	public function purchase_report() {

		$mainobj              = new Mapbd_pos_purchase();
		$response_data        = new API_Data_Response();
		$response_data->limit = $this->get_payload( 'limit', 20 );
		$response_data->page  = $this->get_payload( 'page', 1 );
		$src_props            = $this->get_payload( 'src_by', array() );
		$mainobj->set_search_by_param( $src_props );
		if ( ! POS_Settings::is_admin_user() && ! current_user_can( 'can-see-any-outlet-purchases' ) ) {
			$outlets = get_user_meta( $this->get_current_user_id(), 'outlet_id', true );
			if ( is_array( $outlets ) ) {
				$outlet_in = "'" . implode( "','", $outlets ) . "'";
				$mainobj->warehouse_id( "IN ($outlet_in)", true );
			} else {
				$response_data->set_total_records( 0 );
				return $response_data;
			}
		}
		$order_by = 'purchase_date';
		$order    = 'DESC';
		if ( ! empty( $this->payload['sort_by'][0] ) ) {
			$order_by = $this->payload['sort_by'][0]['prop'];
			$order    = $this->payload['sort_by'][0]['ord'];
		}

		if ( $response_data->set_total_records( $mainobj->count_all() ) ) {
			$outlets                = Mapbd_Pos_Warehouse::find_all_by_key_value( 'status', 'A', 'id', 'name' );
			$response_data->rowdata = $mainobj->select_all_grid_data( '', $order_by, $order, $response_data->limit, $response_data->limit_start() );
			foreach ( $response_data->rowdata as &$data ) {
				$data->purchase_date   = appsbd_get_wp_datetime_with_format( $data->purchase_date );
				$data->discount        = doubleval( $data->discount );
				$data->discount_total  = doubleval( $data->discount_total );
				$data->tax_total       = doubleval( $data->tax_total );
				$data->grand_total     = doubleval( $data->grand_total );
				$data->warehouse_title = appsbd_get_text_by_key( $data->warehouse_id, $outlets );
			}
		}
		return $response_data;
	}

	/**
	 * The product report is generated by appsbd
	 *
	 * @return API_Data_Response
	 */
	public function product_report() {
		$response_data = new API_Data_Response();
		$report        = new Vitepos_Report_Data();
		$src_props     = $this->get_payload( 'src_by', array() );
		$sort_by_props = $this->get_payload( 'sort_by', array() );

		$start_date = null;
		$end_date   = null;
		$outlet_id  = null;
		foreach ( $src_props as $item ) {
			if ( isset( $item['prop'] ) && 'outlet_id' === $item['prop'] ) {
				$outlet_id = $item['val'];
			}
			if ( isset( $item['prop'] ) && 'order_date' === $item['prop'] ) {
				if ( is_array( $item['val'] ) ) {
					$start_date = $item['val']['start'];
					$end_date   = $item['val']['end'];
				} else {
					$start_date = $item['val'];
					$end_date   = $item['val'];
				}
			}
		}
		if ( empty( $outlet_id ) ) {
			$outlet_id = $this->get_outlet_id();
		}

		if ( $this->is_hpos() ) {
			$total_product = ViteposModel::get_db_object()->get_results(
				"
		SELECT COUNT(*) AS total_records
		FROM (
    		SELECT 
        		{$this->posts}.ID AS counted_product_id,
        		{$this->posts}.post_type
    		FROM {$this->posts}
   			WHERE {$this->posts}.post_type IN ('product', 'product_variation') 
      			AND {$this->posts}.post_status IN  ('publish','private')
    		GROUP BY 
        		{$this->posts}.ID
			) AS product_counts
		WHERE 
    		(post_type = 'product' 
    			AND NOT EXISTS (
        		SELECT 1 
        			FROM {$this->posts} AS variations 
       				WHERE variations.post_parent = product_counts.counted_product_id 
        				AND variations.post_type = 'product_variation'
    			)
    		) 
    	OR post_type = 'product_variation';
		"
			);
		} else {
			$total_product = ViteposModel::get_db_object()->get_results(
				"
			SELECT COUNT(*) AS total_records
			FROM (
                SELECT 
                    {$this->posts}.ID AS counted_product_id,
                    {$this->posts}.post_type
                FROM {$this->posts}
                LEFT JOIN {$this->posts} AS variations ON variations.post_parent = {$this->posts}.ID 
                    AND variations.post_type = 'product_variation'
                WHERE {$this->posts}.post_type IN ('product', 'product_variation') 
                    AND {$this->posts}.post_status IN  ('publish','private')
                GROUP BY {$this->posts}.ID
                HAVING ({$this->posts}.post_type = 'product' AND COUNT(variations.ID) = 0)
                    OR {$this->posts}.post_type = 'product_variation'
			) AS product_counts;"
			);
		}

		$page                 = $this->get_payload( 'page', 1 );
		$limit                = $this->get_payload( 'limit', 20 );
		$response_data->page  = $page;
		$response_data->limit = $limit;

		$product_list = $report->product_list( $outlet_id, $start_date, $end_date, $limit, $page );
		foreach ( $product_list as &$product ) {
			if ( ! empty( $product->product_id ) ) {
				$product->image_url = $this->get_product_img_url( $product->product_id, 'full' );
			}
			$barcode_type = POS_Settings::get_module_option( 'barcode_field' );
			if ('CUS' == $barcode_type) {
				$product->barcode = $product->barcode;
			}elseif('SKU' == $barcode_type){
				$product->barcode = $product->sku;
			}elseif('GUI' == $barcode_type){
				$product->barcode = $product->global_unique_id;
			}else{
				$product->barcode = $product->product_id;
			}
		}
		if ( $response_data->set_total_records( $total_product[0]->total_records ) ) {
			$response_data->rowdata = $product_list;
		}

		return $response_data;
	}

