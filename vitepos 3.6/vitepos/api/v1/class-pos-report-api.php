	/**
	 * The dashboard report is generated by appsbd
	 */
	public function dashboard_report() {
		$report        = new Vitepos_Report_Data();
		$src_props     = $this->get_payload( 'src_by', array() );
		$sort_by_props = $this->get_payload( 'sort_by', array() );

		$start_date = null;
		$end_date   = null;
		$outlet_id  = null;
		foreach ( $src_props as $item ) {
			if ( isset( $item['prop'] ) && 'outlet_id' === $item['prop'] ) {
				$outlet_id = $item['val'];
			}
			if ( isset( $item['prop'] ) && 'order_date' === $item['prop'] ) {
				if ( is_array( $item['val'] ) ) {
					$start_date = $item['val']['start'];
					$end_date   = $item['val']['end'];
				} else {
					$start_date = $item['val'];
					$end_date   = $item['val'];
				}
			}
		}
		if ( empty( $outlet_id ) ) {
			$outlet_id = $this->get_outlet_id();
		}
		
		$order_data = $report->day_wise_order( $outlet_id, $start_date, $end_date );

		
		$top_orders = $report->top_orders( $outlet_id, $start_date, $end_date, 'wc-completed' );

		
		$top_refunds = $report->top_orders( $outlet_id, $start_date, $end_date, 'wc-refunded' );

		
		$payment_method_data = $report->payment_methods_report( $outlet_id, $start_date, $end_date );

		
		$product_data = $report->top_products( $outlet_id, $start_date, $end_date );
		foreach ( $product_data as &$product ) {
			if ( ! empty( $product->ID ) ) {
				$product->product_img = $this->get_product_img_url( $product->ID, 'full' );
			}
		}

		
		$customer_data = $report->top_customers( $outlet_id, $start_date, $end_date );
		foreach ( $customer_data as &$customer ) {
			if ( $customer->user_email ) {
				$customer->customer_img = $this->get_gravatar_url( $customer->user_email, 'full' );
			} else {
				$customer->customer_img = $this->get_gravatar_url( null );
			}
		}

		
		$staff_data = $report->top_staffs( $outlet_id, $start_date, $end_date );
		foreach ( $staff_data as &$staff ) {
			if ( $staff->user_email ) {
				$staff->staff_img = $this->get_gravatar_url( $staff->user_email, 'full' );
			} else {
				$staff->staff_img = $this->get_gravatar_url( null );
			}
		}

		$response_data = array(
			'order_data'           => $order_data,
			'payment_method_data'  => $payment_method_data,
			'product_data'         => $product_data,
			'staff_data'           => $staff_data,
			'customer_data'        => $customer_data,
			'top_orders'           => $top_orders,
			'top_refunds'          => $top_refunds,
		);

		
		$tax_display_totals = get_option( 'woocommerce_tax_total_display', 'single' );
		if ( 'itemized' === $tax_display_totals ) {
			$rate_wise_tax_totals = $report->rate_wise_tax_total($outlet_id,$start_date,$end_date);
			$response_data['rate_wise_tax_totals'] = $rate_wise_tax_totals;
		}

		$this->response->set_response( true, '', $response_data );

		return $this->response;
	}

	/**
	 * The get gravatar url is generated by appsbd
	 *
	 * @param mixed $email It is email param.
	 * @param int $size It is size param.
	 *
	 * @return string
	 */
	public function get_gravatar_url( $email, $size = 50 ) {
		if ( $email ) {
			$grav_url = 'https://www.gravatar.com/avatar/' . md5( strtolower( trim( $email ) ) ) . '?s=' . $size;
		} else {
			$grav_url = 'https://www.gravatar.com/avatar/00000000000000000000000000000000?d=mp&f=y';
		}

		return $grav_url;
	}

	/**
	 * The get product img url is generated by appsbd
	 *
	 * @param mixed $id It is i param.
	 * @param mixed $size It is s param.
	 */
	public function get_product_img_url( $id, $size = 50 ) {
		$product = wc_get_product( $id );
		if ( ! $product ) {
			return false;
		}
		$image_id = $product->get_image_id();
		if ( ! empty( $image_id ) ) {
			return wp_get_attachment_image_url( $image_id, $size );
		} else {
			return false;
		}
	}

	/**
	 * The set limit is generated by appsbd
	 *
	 * @param float|int $data It is data param.
	 *
	 * @return float|int
	 */
	public function set_limit( $data ) {
		$ceil_data = ceil( $data / 50 );

		return ( 50 * $ceil_data ) / 5;
	}
