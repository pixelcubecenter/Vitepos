	/**
	 * The get property raw options is generated by appsbd
	 *
	 * @param mixed   $property Its the property.
	 * @param boolean $is_with_select False if with select.
	 *
	 * @return array|string[]
	 */
	public function get_property_raw_options( $property, $is_with_select = false ) {
		$return_obj = array();
		switch ( $property ) {
			case 'log_type':
				$return_obj = array(
					'D' => 'Debit',
					'C' => 'Credit',
				);
				break;
			case 'ref_type':
				$return_obj = array(
					'O' => 'Order',
					'C' => 'Close',
					'W' => 'Withdraw',
				);
				break;
			default:
		}
		if ( $is_with_select ) {
			return array_merge( array( '' => 'Select' ), $return_obj );
		}
		return $return_obj;
	}


	/**
	 * The AddLog is generated by appsbd
	 *
	 * @param mixed $cash_drawer_id It is cash_drawer_id param.
	 * @param mixed $note It is note param.
	 * @param mixed $pre_balance It is pre_balance param.
	 * @param mixed $amount It is amount param.
	 * @param mixed $log_type It is log_type param.
	 * @param mixed $ref_type It is ref_type param.
	 * @param mixed $ref_id It is ref_id param.
	 * @param mixed $user_note It is user_note param.
	 * @param mixed $extra_param It is extra_param param.
	 *
	 * @return bool
	 */
	public static function AddLog( $cash_drawer_id, $note, $pre_balance, $amount, $log_type, $ref_type, $ref_id, $user_note = '', $extra_param = '' ) {
		$newobj = new self();
		$newobj->cash_drawer_id( $cash_drawer_id );
		$newobj->user_id( get_current_user_id() );
		$newobj->note( $note );
		$newobj->pre_balance( $pre_balance );
		$newobj->amount( $amount );
		$newobj->log_type( $log_type ); 
		$newobj->user_note( $user_note ); 
		$newobj->extra_param( $extra_param ); 
		$newobj->ref_type( $ref_type ); 
		$newobj->ref_id( $ref_id ); 
		$newobj->entry_time( gmdate( 'Y-m-d H:i:s' ) );
		return $newobj->save();
	}
