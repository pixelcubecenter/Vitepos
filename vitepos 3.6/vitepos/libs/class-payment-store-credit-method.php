<?php
/**
 * Its "Store Credit" redemption tender.
 *
 * Lets a customer redeem their positive store-credit balance (accrued from
 * repayment overpayments or purchased top-ups) against a new purchase. The
 * applied amount is a payment_list line (type 'X'); process_payment() validates
 * it does not exceed the available balance, and the balance is decremented on
 * `appsbd/vitepos/action/vt-order-complete` (see POS_Payment module).
 *
 * The method is always available (not admin-toggled); the POS only shows it for
 * a selected customer whose store_credit > 0 (client-side gate).
 *
 * @package VitePos\Libs
 */

namespace VitePos\Libs;

use VitePos\Modules\POS_Settings;

/**
 * Class Payment_Store_Credit_Method
 *
 * @package VitePos\Libs
 */
class Payment_Store_Credit_Method extends Payment_Method_Base {

	/**
	 * The initialize is generated by appsbd
	 *
	 * @return mixed|void
	 */
	public function initialize() {
		$this->set_admin_name( 'store_credit' );
		$this->set_admin_viewable( false );
		$this->title   = 'Store Credit';
		$this->icon    = 'vps vps-credit-02';
		$this->id      = 'X';
		$this->comp    = 'basic';
		$this->split   = true;
		$this->offline = false;
		$this->add_field( 'Note', 'payment_note' );
	}

	/**
	 * The set admin settings is generated by appsbd
	 *
	 * @return mixed|void
	 */
	public function set_admin_settings() {
		$this->set_admin_title_desc(
			'Enable Store Credit',
			'Allows customers to redeem their store-credit balance on a purchase.'
		);
	}

	/**
	 * Validate the redeemed amount against the available balance.
	 *
	 * @param \stdClass  $params Its params param.
	 * @param string     $currency_code Its currency_code param.
	 * @param \WC_Order  $order Its order param.
	 * @param int|string $outlet_id Its outlet_id param.
	 * @param int|string $counter_id Its counter_id param.
	 *
	 * @return \stdClass
	 */
	public function process_payment( $params, $currency_code, $order, $outlet_id, $counter_id ) {
		$amount      = isset( $params->payment_item['amount'] ) ? (float) $params->payment_item['amount'] : 0;
		$customer_id = (int) $order->get_customer_id();
		if(!$customer_id)
		{
			POS_Settings::get_module_instance()->add_error(
				__( 'Customer is not selected.', 'vitepos' )
			);
			$params->resp->status    = true;
			$params->resp->is_delete = true;
			return $params;
		}

		
		
		if ( ! VitePOS_Account_Service::is_enabled($customer_id) ) {
			POS_Settings::get_module_instance()->add_error(
				__( 'The Store Credit payment method is disabled.', 'vitepos' )
			);
			$params->resp->status    = true;
			$params->resp->is_delete = true;
			return $params;
		}




		$balance     = \VitePos\Libs\VitePOS_Account_Service::get_credit_balance( $customer_id );

		if ( $amount > $balance + 0.0001 ) {
			\VitePos\Modules\POS_Settings::get_module_instance()->add_error(
				sprintf(
					/* translators: 1: requested, 2: available */
					__( 'Store credit %1$s exceeds the available balance %2$s.', 'vitepos' ),
					wc_price( $amount ),
					wc_price( $balance )
				)
			);
			$params->resp->status    = true;
			$params->resp->is_delete = true;
			return $params;
		}
		return $params;
	}
}
