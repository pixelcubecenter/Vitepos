<?php
/**
 * Its "Debt / On Account" payment method.
 *
 * Lets approved credit customers defer payment as debt. The deferred amount is
 * modelled as its own payment_list line (type 'N') so the checkout's
 * `given_amount >= grand_total` guard still passes. The credit-limit check runs
 * server-side here in process_payment(); the debt row itself is created later on
 * the `appsbd/vitepos/action/vt-order-complete` hook (see POS_Payment module).
 *
 * @package VitePos\Libs
 */

namespace VitePos\Libs;

use VitePos\Modules\POS_Settings;

/**
 * Class Payment_On_Account_Method
 *
 * @package VitePos\Libs
 */
class Payment_On_Account_Method extends Payment_Method_Base {
	/**
	 * Summary of default_limit
	 * @var int
	 */
	protected $default_limit=100;
	/**
	 * Default for the single-item-without-limit switch ('Y'/'N').
	 *
	 * @var string
	 */
	protected $default_single_unlimited='N';
	/**
	 * Saved single-item-without-limit flag ('Y'/'N'), mirrored from the admin
	 * setting. Public so it serializes to the POS client — the client receives
	 * only the method's public properties, not admin_data.
	 *
	 * @var string
	 */
	public $single_unlimited='N';
	/**
	 * The initialize is generated by appsbd
	 *
	 * @return mixed|void
	 */
	public function initialize() {
		$this->set_admin_name( 'on_account' );
		$this->set_admin_viewable( true );
		$this->title   = 'Debt';
		$this->icon    = 'vps vps-debt-05';
		$this->id      = 'N';
		$this->comp    = 'basic';
		$this->split   = true;
		$this->offline = false;
		$this->add_field( 'Note', 'payment_note' );
	}

	
	/**
	 * The after loaded is generated by appsbd
	 */
	public function after_loaded() {
		if ( ! isset( $this->admin_data->settings['default_limit'] ) ) {
			$this->admin_data->settings['default_limit']    = $this->default_limit;
			$this->admin_data->settings['single_unlimited'] = $this->default_single_unlimited;
		}
		
		$this->single_unlimited = ( 'Y' === $this->get_admin_setting( 'single_unlimited' ) ) ? 'Y' : 'N';
	}


	/**
	 * The set admin settings is generated by appsbd
	 *
	 * @return mixed|void
	 */
	public function set_admin_settings() {
		$this->set_admin_title_desc(
			'Enable Debt / On Account',
			'Allows approved credit customers to defer payment as debt.'
		);
		$this->set_tab_title( 'Debt / On Account Settings', 'vps vps-payment-method' );

		$stripe_settings_card = $this->add_admin_card( 'settings', 'Debt / On Account' );

		$stripe_settings_card->add_settings_field(	
			'Default Credit Limit',
			'default_limit',
			false,
			'N'
		);

		$stripe_settings_card->add_settings_field(
			'Enable Single Item Purchase Without Limit',
			'single_unlimited',
			false,
			'S',
			array(
				'true_val'  => 'Y',
				'false_val' => 'N',
			)
		);
		$stripe_settings_card->add_description('If enabled, customers can purchase a single item on account even if it exceeds the account purchase limit.','text-warning');
	}

	/**
	 * Server-side credit gate. Runs inside is_ok_all_payment() for the
	 * on-account line. Setting resp->is_delete=true rejects and deletes the order.
	 *
	 * @param \stdClass  $params Its params param.
	 * @param string     $currency_code Its currency_code param.
	 * @param \WC_Order  $order Its order param.
	 * @param int|string $outlet_id Its outlet_id param.
	 * @param int|string $counter_id Its counter_id param.
	 *
	 * @return \stdClass
	 */
	public function process_payment( $params, $currency_code, $order, $outlet_id, $counter_id ) {
		
		
		if ( ! VitePOS_Account_Service::is_feature_enabled() ) {
			POS_Settings::get_module_instance()->add_error(
				__( 'The Debt / On Account payment method is disabled.', 'vitepos' )
			);
			$params->resp->status    = true;
			$params->resp->is_delete = true;
			return $params;
		}
		$amount      = isset( $params->payment_item['amount'] ) ? (float) $params->payment_item['amount'] : 0;
		$customer_id = $order->get_customer_id();

		
		
		if ( ! VitePOS_Account_Service::is_enabled($customer_id) ) {
			POS_Settings::get_module_instance()->add_error(
				__( 'The Debt / On Account payment method is disabled.', 'vitepos' )
			);
			$params->resp->status    = true;
			$params->resp->is_delete = true;
			return $params;
		}

		$item_count     = 0;
		$total_quantity = 0;
		foreach ( $order->get_items() as $item ) {
			$item_count++;
			$total_quantity += (int) $item->get_quantity();
		}

		$check = VitePOS_Credit_Validator::can_purchase( $customer_id, $amount, $item_count, $total_quantity );
		if ( ! $check->is_ok ) {
			POS_Settings::get_module_instance()->add_error( $check->message );
			$params->resp->status    = true;
			$params->resp->is_delete = true;
			return $params;
		}

		
		
		return $params;
	}

	/**
	 * The is admin viewable is generated by appsbd
	 *
	 * @return bool
	 */
	public function is_admin_viewable() {
		try {
			if(POS_Settings::get_pos_mode()!='G') {
				return false;
			}
			return $this->admin_data->is_viewable();
		} catch ( \Exception $e ) {
			return true;
		}
	}
}
