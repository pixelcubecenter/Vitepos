		 * The get counter obj is generated by appsbd
		 *
		 * @return Mapbd_Pos_Counter|null
		 */
		public function get_counter_obj() {
			if ( ! empty( self::$counter_id ) && ! empty( self::$counter_id ) ) {
				self::$counter_obj = Mapbd_Pos_Counter::find_by( 'id', self::$counter_id );
			}
			return self::$counter_obj;
		}

		/**
		 * The load payload is generated by appsbd
		 */
		public function load_payload() {
			if ( ! self::$is_loaded_payload ) {
				$req_type = get_request_content_type();
				if ( ! empty( $req_type ) ) {
					$req_type = strtolower( get_request_content_type() );
				}

				if ($req_type === 'application/json') {
					self::$payload_obj = json_decode(file_get_contents('php://input'), true);
				}
				elseif ($req_type === 'application/x-www-form-urlencoded') {
					parse_str(file_get_contents('php://input'), self::$payload_obj);
				}
				else {
					self::$payload_obj = AppInput::get_posted_data();
				}
				self::$is_loaded_payload = true;
				$vite_outlet             = AppInput::get_server_data( 'HTTP_VITE_OUTLET' );
				$request_outlet_counter  = ! empty( $vite_outlet ) ? explode( '|', $vite_outlet ) : array();
				if ( ! empty( $request_outlet_counter[0] ) ) {
					self::$outlet_id = $request_outlet_counter[0];
				}
				if ( ! empty( $request_outlet_counter[1] ) ) {
					self::$counter_id = $request_outlet_counter[1];
				}
			}
			$this->payload =&self::$payload_obj;

			$this->checkFileType();

			$this->set_payload_int(['limit','page']);
		}

		/**
		 * The set payload int is generated by appsbd
		 *
		 * @param mixed $keys It is keys param.
		 */
		public function set_payload_int($keys){
			foreach ( $keys as $key ) {
				if(isset( $this->payload[ $key ] ) && is_numeric($this->payload[ $key ]) && ctype_digit(strval($this->payload[ $key ]))) {
					$this->payload[ $key ]=(int)$this->payload[ $key ];
				}
			}

		}

		/**
		 * The checkFileType is generated by appsbd
		 */
		public function checkFileType() {
			if (empty($_FILES)) {
				return;
			}

			$allowed_mimes = [
				'jpg|jpeg|jpe' => 'image/jpeg',
				'png'          => 'image/png',
				'gif'          => 'image/gif',
				'webp'         => 'image/webp',
			];

			$files = $this->flattenFilesArray($_FILES);

			foreach ($files as $file) {

				if (empty($file['name']) || empty($file['tmp_name'])) {
					continue;
				}

				$validate = wp_check_filetype_and_ext(
					$file['tmp_name'],
					$file['name'],
					$allowed_mimes
				);

				if (empty($validate['ext']) || empty($validate['type'])) {
					$this->add_error('Uploaded file type not allowed');
					wp_send_json($this->response->get_response(), 200);
				}
			}
		}

		public function flattenFilesArray($files) {
			$output = [];

			foreach ($files as $key => $fileGroup) {
				if (!is_array($fileGroup['name'])) {
					
					$output[] = $fileGroup;
				} else {
					
					foreach ($fileGroup['name'] as $idx => $names) {
						foreach ($names as $subKey => $name) {
							$output[] = [
								'name'     => $name,
								'type'     => $fileGroup['type'][$idx][$subKey],
								'tmp_name' => $fileGroup['tmp_name'][$idx][$subKey],
								'error'    => $fileGroup['error'][$idx][$subKey],
								'size'     => $fileGroup['size'][$idx][$subKey],
							];
						}
					}
				}
			}

			return $output;
		}



