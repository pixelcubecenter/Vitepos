		 */
		public function get_outlet_obj() {
			if ( ! empty( self::$outlet_id ) && empty( self::$outlet_obj->name ) ) {
				static::$outlet_obj = Mapbd_Pos_Warehouse::find_by( 'id', self::$outlet_id );
			}
			return static::$outlet_obj;
		}

